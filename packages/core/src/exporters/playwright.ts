/** Build a locator expression, collapsing `candidates` into `firstMatch`. */
function locatorExpr(selector: SelectorSpec): string {
  if (typeof selector === 'string') return `page.locator(${JSON.stringify(selector)})`;
  if ('candidates' in selector) {
    const parts = selector.candidates.map((candidate) => candidateToExpression(candidate));
    return `(await firstMatch(page, [${parts.join(', ')}]))`;
  }
  return `page.locator(${JSON.stringify(candidateToPlaywrightSelector(selector))})`;
}

/** For `candidates`, each entry is either a plain string or a factory. */
function candidateToExpression(selector: SelectorSpec): string {
  const rendered = candidateToPlaywrightSelector(selector);
  return JSON.stringify(rendered);
}

/** Convert one SelectorSpec variant into a Playwright selector string. */
export function candidateToPlaywrightSelector(selector: SelectorSpec): string {
  if (typeof selector === 'string') return selector;
  if ('candidates' in selector) return candidateToPlaywrightSelector(selector.candidates[0]!);
  if ('testId' in selector) return `[data-testid="${escapeAttr(selector.testId)}"]`;
  if ('role' in selector) {
    return selector.name
      ? `role=${selector.role}[name="${escapeAttr(selector.name)}"]`
      : `role=${selector.role}`;
  }
  if ('text' in selector)
    return selector.exact ? `text="${selector.text}"` : `text=${selector.text}`;
  if ('css' in selector) return selector.css;
  if ('xpath' in selector) return `xpath=${selector.xpath}`;
  const exhaustive: never = selector;
  return String(exhaustive);
}

/** Interpolate `{{var}}` into a template literal referencing `vars`. */
function tpl(value: string): string {
  if (!value.includes('{{')) return JSON.stringify(value);
  const inner = value
    .split(/(\{\{\s*[A-Za-z0-9_.\-[\]$]+\s*\}\})/)
    .map((part) => {
      const match = /^\{\{\s*([A-Za-z0-9_.\-[\]$]+)\s*\}\}$/.exec(part);
      if (match) return `\${vars[${JSON.stringify(match[1])}]}`;
      return part.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
    })
    .join('');
  return `\`${inner}\``;
}

function renderUrlMatcher(pattern: string): string {
  if (pattern.startsWith('/') && pattern.lastIndexOf('/') > 0) {
    const end = pattern.lastIndexOf('/');
    return `new RegExp(${JSON.stringify(pattern.slice(1, end))}, ${JSON.stringify(pattern.slice(end + 1))})`;
  }
  if (pattern.includes('*')) {
    const escaped = pattern.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*');
    return `new RegExp(${JSON.stringify(`^${escaped}$`)})`;
  }
  return JSON.stringify(pattern);
}

/** Render a `Condition` as an awaitable boolean expression. */
function renderCondition(condition: Condition): string {
  if ('pageIs' in condition) {
    return `true /* pageIs: "${condition.pageIs}" — fingerprints are host-side; adjust as needed */`;
  }
  if ('varEquals' in condition) {
    const name = JSON.stringify(condition.varEquals.name);
    const expected = JSON.stringify(condition.varEquals.value);
    return `JSON.stringify(vars[${name}]) === ${JSON.stringify(expected)}`;
  }
  if ('selectorExists' in condition) {
    return `(await ${locatorExpr(condition.selectorExists)}.count()) > 0`;
  }
  if ('not' in condition) return `!(${renderCondition(condition.not)})`;
  if ('all' in condition) {
    const parts = condition.all.map((c) => `(${renderCondition(c)})`);
    return parts.length > 0 ? parts.join(' && ') : 'true';
  }
  if ('any' in condition) {
    const parts = condition.any.map((c) => `(${renderCondition(c)})`);
    return parts.length > 0 ? parts.join(' || ') : 'false';
  }
  const exhaustive: never = condition;
  return String(exhaustive);
}

function renderLoopItems(step: Extract<Step, { type: 'loop' }>): string {
  if (Array.isArray(step.items)) return renderValue(step.items);
  if (step.items.includes('{{')) return tpl(step.items);
  return `vars[${JSON.stringify(step.items)}] ?? []`;
}

function renderValue(value: unknown): string {
  return JSON.stringify(value) ?? 'undefined';
}

function renderVariable(name: string, def: VariableDef): string {
  switch (def.type) {
    case 'const':
      return JSON.stringify(def.value) ?? 'undefined';
    case 'env':
    case 'secret':
      return def.default !== undefined
        ? `process.env[${JSON.stringify(def.key)}] ?? ${JSON.stringify(def.default)}`
        : `process.env[${JSON.stringify(def.key)}]`;
    case 'input': {
      const envKey = `ROBO_${name.toUpperCase().replace(/\W+/g, '_')}`;
      return def.default !== undefined
        ? `process.env[${JSON.stringify(envKey)}] ?? ${JSON.stringify(def.default)}`
        : `process.env[${JSON.stringify(envKey)}] ?? ''`;
    }
    default: {
      const exhaustive: never = def;
      return String(exhaustive);
    }
  }
}

function quoteKey(key: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

function escapeAttr(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}
