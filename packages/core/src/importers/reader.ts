/**
 * Shared import orchestration.
 *
 * The Playwright and raw-CDP exporters emit *byte-identical* source for the
 * structural steps (`branch`, `loop`, `setVar`, `httpCall`), for the step anchor
 * comments (`// <id>: <type>`) and for the `const vars = { … }` block. Those
 * shapes are recovered here once; each importer only has to recognise its own
 * statement vocabulary and delegate the rest.
 */
import type {
  BranchStep,
  Condition,
  HttpCallStep,
  LoopStep,
  SelectorSpec,
  SetVarStep,
  Step,
  VariableDef,
} from '../flow/schema.js';
import type { ManualReason } from '../handlers/manual.js';
import type { ImportWarning } from './types.js';
import * as S from './source.js';

/** Every `Step['type']` tag, used to validate anchor comments. */
export const STEP_TYPES = [
  'goto',
  'click',
  'type',
  'select',
  'hover',
  'scroll',
  'waitForPage',
  'waitForSelector',
  'waitForUrl',
  'waitForNetworkIdle',
  'waitForDownload',
  'extract',
  'screenshot',
  'branch',
  'loop',
  'setVar',
  'httpCall',
  'manual',
] as const;

const STEP_TYPE_SET = new Set<string>(STEP_TYPES);

/** True for a non-null, non-array object. */
export function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** State shared by one import run: warnings and the step id allocator. */
export class ImportContext {
  public readonly warnings: ImportWarning[] = [];
  private readonly used = new Set<string>();

  /** Record a non-fatal problem with the source line it was found on. */
  public warn(line: number, message: string, snippet?: string): void {
    this.warnings.push(snippet === undefined ? { line, message } : { line, message, snippet });
  }

  /**
   * Allocate a unique step id.
   *
   * @param suggested - Id from the anchor comment, when present.
   * @param fallback - Step type used when the comment carried no id.
   */
  public uniqueId(suggested: string | undefined, fallback: string): string {
    const base = sanitizeId(suggested ?? '') || sanitizeId(fallback) || 'step';
    let candidate = base;
    let suffix = 2;
    while (this.used.has(candidate)) {
      candidate = `${base}-${suffix}`;
      suffix += 1;
    }
    this.used.add(candidate);
    return candidate;
  }
}

/** Restrict an id to the characters FlowModel authors use in practice. */
function sanitizeId(value: string): string {
  return value
    .trim()
    .replace(/[^A-Za-z0-9_-]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/** Target-specific hooks the shared parsers need. */
export interface StepHooks {
  /** Recover a {@link SelectorSpec} from a locator / selector expression. */
  resolveSelector(expr: string): SelectorSpec | null;
  /** Recover a {@link Condition} from a rendered boolean expression. */
  parseCondition(text: string): Condition | null;
}

/** Parse a token list into steps (supplied by the concrete reader). */
export type BlockParser = (items: S.ScanItem[]) => Step[];

/* ------------------------------------------------------------------- header */

/** Metadata recovered from the script header comments. */
export interface ScriptHeader {
  /** True when the script carries the RoboBrowser banner. */
  generated: boolean;
  /** Flow name from `// Flow: <name> (<id>)`, when present. */
  name: string | null;
  /** Flow id from `// Flow: <name> (<id>)`, when present. */
  id: string | null;
}

/** Recover flow name / id and the "generated" flag from header comments. */
export function parseHeader(source: string): ScriptHeader {
  const generated = source.includes('AUTO-GENERATED by RoboBrowser');
  const match = /^\/\/\s*Flow:\s*(.*)\s*\(([^()]*)\)\s*$/m.exec(source);
  if (!match) return { generated, name: null, id: null };
  return { generated, name: match[1]?.trim() || null, id: match[2]?.trim() || null };
}

/* ------------------------------------------------------------------- anchor */

/** A `// <id>: <type>` anchor emitted before each exported step. */
export interface StepAnchor {
  id: string;
  type: string;
}

/** Recover the step anchor from a standalone comment, when it is one. */
export function parseAnchor(comment: S.ScanComment): StepAnchor | null {
  const body = comment.block
    ? comment.text
        .replace(/^\/\*+/, '')
        .replace(/\*+\/$/, '')
        .trim()
    : comment.text.replace(/^\/+/, '').trim();
  const match = /^(.+?):\s*([A-Za-z][A-Za-z0-9]*)$/.exec(body);
  if (!match) return null;
  const type = match[2] ?? '';
  if (!STEP_TYPE_SET.has(type)) return null;
  return { id: (match[1] ?? '').trim(), type };
}

/* -------------------------------------------------------------- boilerplate */

/** Statements the exporters emit as scaffolding; skipped without a warning. */
const BOILERPLATE: readonly RegExp[] = [
  /^const executablePath\s*=/,
  /^const browser\s*=/,
  /^const context\s*=/,
  /^const page\s*=/,
  /^const wsUrl\s*=/,
  /^if\s*\(\s*!wsUrl\s*\)/,
  /^const cdp\s*=/,
  /^await\s+cdp\.send\(\s*['"](?:Page|Runtime|DOM)\.enable['"]/,
  /^const artifacts\s*=\s*\[\s*\]/,
  /^const outDir\s*=/,
  /^const nextDownload\s*=/,
  /^await\s+browser\.close\(\)/,
  /^console\.log\(\s*JSON\.stringify\(/,
  /^artifacts\.push\(/,
  /^console\.log\(\s*["']extracted\s/,
  /^if\s*\(\s*!res\.ok\s*\)/,
  /^await\s+download\.saveAs\(/,
  /^const target\s*=\s*path\.join\(outDir,\s*download\.suggestedFilename\(\)\)$/,
];

/** True when a body statement is exporter scaffolding rather than a step. */
export function isBoilerplate(text: string): boolean {
  const trimmed = text.trim();
  return BOILERPLATE.some((pattern) => pattern.test(trimmed));
}

/* ---------------------------------------------------------------- variables */

/**
 * Recover the `variables` map from the `const vars = { … };` body.
 *
 * Note the two documented losses: `secret` and `env` declarations are emitted
 * identically (`process.env["KEY"]`), so env wins; and an `input` label is not
 * emitted at all, so the variable name is used instead.
 */
export function parseVariablesBlock(
  body: string,
  ctx: ImportContext,
  line: number,
): Record<string, VariableDef> {
  const out: Record<string, VariableDef> = {};
  for (const entry of S.splitTopLevel(body, ',')) {
    const kv = S.splitObjectEntry(entry);
    if (!kv) {
      ctx.warn(line, `变量条目无法解析：${entry}`, entry);
      continue;
    }
    const key = S.parseObjectKey(kv.key);
    if (key === null) {
      ctx.warn(line, `变量名无法解析：${kv.key}`, entry);
      continue;
    }
    out[key] = recoverVariable(key, kv.value, ctx, line);
  }
  return out;
}

/** Recover a single variable declaration from its value expression. */
function recoverVariable(name: string, expr: string, ctx: ImportContext, line: number): VariableDef {
  const env = S.parseEnvLookup(expr);
  if (env) {
    const fallback = env.fallback === null ? null : S.parseStringExpr(env.fallback);
    if (env.key === `ROBO_${name.toUpperCase().replace(/\W+/g, '_')}`) {
      ctx.warn(
        line,
        `变量「${name}」按 input 还原（label 用变量名，原 label 未写入脚本；如为 const 请手动改回）`,
      );
      return fallback === null
        ? { type: 'input', label: name }
        : { type: 'input', label: name, default: fallback };
    }
    ctx.warn(
      line,
      `变量「${name}」按 env 还原（env 与 secret 的脚本形式完全相同，如需脱敏请手动改为 secret）`,
    );
    return fallback === null
      ? { type: 'env', key: env.key }
      : { type: 'env', key: env.key, default: fallback };
  }

  const literal = S.parseJsLiteral(expr);
  if (literal.ok) return { type: 'const', value: literal.value };
  ctx.warn(line, `变量「${name}」无法还原：${literal.reason}`, expr);
  return { type: 'const', value: null };
}

/* ------------------------------------------------------------------- branch */

/** Recover a `branch` step from an `if (…) { … } else { … }` statement. */
export function parseBranchStatement(
  text: string,
  ctx: ImportContext,
  hooks: StepHooks,
  parseBlock: BlockParser,
  anchor: StepAnchor | null,
  line: number,
): BranchStep | null {
  const split = S.splitIfElse(text);
  if (!split) return null;
  const condition = hooks.parseCondition(split.condition);
  if (!condition) {
    ctx.warn(line, `分支条件无法还原：${split.condition}`, text);
    return null;
  }
  const step: BranchStep = {
    id: ctx.uniqueId(anchor?.id, 'branch'),
    type: 'branch',
    condition,
    then: parseBlock(S.tokenize(split.thenBody)),
  };
  const otherwise = split.elseBody === null ? [] : parseBlock(S.tokenize(split.elseBody));
  if (otherwise.length > 0) step.else = otherwise;
  return step;
}

/* --------------------------------------------------------------------- loop */

/** Recover a `loop` step from the exported `{ const items …; for (…) { … } }`. */
export function parseLoopBlock(
  text: string,
  ctx: ImportContext,
  parseBlock: BlockParser,
  anchor: StepAnchor | null,
  line: number,
): LoopStep | null {
  const body = S.firstBlockBody(text);
  if (body === null) return null;
  const items = S.tokenize(body);
  const declaration = items[0];
  const loop = items[1];
  if (!declaration || declaration.kind !== 'stmt' || !loop || loop.kind !== 'stmt') return null;

  const decl = S.splitConstDeclaration(declaration.text);
  if (!decl || decl.target !== 'items') return null;

  const forSplit = S.splitFor(loop.text);
  if (!forSplit) return null;
  const inner = S.tokenize(forSplit.body);
  const head = inner[0];
  if (!head || head.kind !== 'stmt') return null;
  const assign = S.splitAssignment(head.text);
  const as = assign ? S.parseVarsLookup(assign.target)?.name : undefined;
  if (!as) {
    ctx.warn(line, '循环体缺少 `vars[as] = items[i]` 赋值，无法还原循环变量', head.text);
    return null;
  }

  return {
    id: ctx.uniqueId(anchor?.id, 'loop'),
    type: 'loop',
    items: recoverLoopItems(decl.value),
    as,
    steps: parseBlock(inner.slice(1)),
  };
}

/** `loop.items` is an array literal, a `vars[…]` lookup, or a `{{…}}` string. */
function recoverLoopItems(expr: string): string | unknown[] {
  const literal = S.parseJsLiteral(expr);
  if (literal.ok && Array.isArray(literal.value)) return literal.value;
  const lookup = S.parseVarsLookup(expr);
  if (lookup) return lookup.name;
  const text = S.parseStringExpr(expr);
  return text ?? [];
}

/* --------------------------------------------------------------- conditions */

/**
 * Recover a flow {@link Condition} from a rendered boolean expression.
 *
 * Both exporters render `all` / `any` by wrapping *every* operand in
 * parentheses, so `(x)` is ambiguous: it is a one-element `all` at a logical
 * position, but merely a wrapped operand inside a chain. The three-level walk
 * below resolves that — {@link parseLogical} trusts the wrapper, while
 * {@link parseOperand} knows it belongs to the enclosing chain.
 *
 * @param text - Rendered expression, e.g. `(a) && ((b) || (c))`.
 * @param parser - Target-specific leaf recovery.
 */
export function parseConditionExpression(text: string, parser: ConditionParser): Condition | null {
  return parseLogical(text.trim(), parser);
}

/** Target-specific hooks used by {@link parseConditionExpression}. */
export interface ConditionParser {
  /** Recover a leaf condition. */
  atomic(text: string): Condition | null;
  /**
   * Optional: recognise a leaf that *already renders parenthesised* (the
   * raw-CDP `selectorExists` is emitted as `(await evaluate(cdp, …))`). Without
   * this the wrapper would be re-read as a one-element `all`, adding a pair of
   * parentheses on re-export.
   */
  unwrap?(inner: string): Condition | null;
}

/** A logical position: a full wrapper here means a one-element `all`. */
function parseLogical(t: string, parser: ConditionParser): Condition | null {
  if (t.startsWith('(') && S.findMatching(t, 0) === t.length - 1) {
    const inner = S.innerOf(t, 0);
    const selfParenthesised = parser.unwrap?.(inner);
    if (selfParenthesised !== null && selfParenthesised !== undefined) return selfParenthesised;
    const wrapped = parseLogical(inner, parser);
    return wrapped === null ? null : { all: [wrapped] };
  }
  return parseChain(t, parser);
}

/** Split a chain into its operands; a single operand falls through. */
function parseChain(t: string, parser: ConditionParser): Condition | null {
  const andParts = S.splitTopLevel(t, '&&');
  if (andParts.length > 1) {
    const parts: Condition[] = [];
    for (const part of andParts) {
      const condition = parseOperand(part, parser);
      if (condition === null) return null;
      parts.push(condition);
    }
    return { all: parts };
  }

  const orParts = S.splitTopLevel(t, '||');
  if (orParts.length > 1) {
    const parts: Condition[] = [];
    for (const part of orParts) {
      const condition = parseOperand(part, parser);
      if (condition === null) return null;
      parts.push(condition);
    }
    return { any: parts };
  }

  return parser.atomic(t);
}

/** One operand of a chain: its wrapper belongs to the chain, not to an `all`. */
function parseOperand(t: string, parser: ConditionParser): Condition | null {
  const s = t.trim();
  if (s.startsWith('(') && S.findMatching(s, 0) === s.length - 1) {
    return parseLogical(S.innerOf(s, 0), parser);
  }
  return parseChain(s, parser);
}

/* ------------------------------------------------------------------ setVar */

/** Recover a `setVar` step from `vars["name"] = <literal>;`. */
export function parseSetVarAssignment(
  target: string,
  value: string,
  ctx: ImportContext,
  anchor: StepAnchor | null,
  line: number,
): SetVarStep | null {
  const name = S.parseVarsLookup(target)?.name;
  if (!name) return null;
  const literal = S.parseJsLiteral(value);
  if (!literal.ok) {
    ctx.warn(line, `setVar 的值无法还原：${literal.reason}`, value);
    return null;
  }
  return { id: ctx.uniqueId(anchor?.id, 'setVar'), type: 'setVar', name, value: literal.value };
}

/* ---------------------------------------------------------------- httpCall */

/**
 * Recover an `httpCall` step from the exported block:
 *
 * ```js
 * {
 *   const res = await fetch(<url>, { method, headers, body });
 *   if (!res.ok) throw new Error('HTTP ' + res.status);
 *   vars["into"] = await res.json().catch(() => res.text());
 * }
 * ```
 */
export function parseHttpCallBlock(
  text: string,
  ctx: ImportContext,
  anchor: StepAnchor | null,
  line: number,
): HttpCallStep | null {
  const body = S.firstBlockBody(text);
  if (body === null) return null;

  let url: string | null = null;
  let method = 'GET';
  let headers: Record<string, string> | undefined;
  let requestBody: unknown;
  let into: string | undefined;

  for (const item of S.tokenize(body)) {
    if (item.kind !== 'stmt') continue;

    const decl = S.splitConstDeclaration(item.text);
    if (decl && decl.target === 'res') {
      const expr = S.stripAwait(decl.value);
      if (expr.startsWith('fetch(')) {
        const args = S.splitTopLevel(S.innerOf(expr, 'fetch'.length), ',');
        url = args[0] === undefined ? null : S.parseStringExpr(args[0]);
        if (args[1] !== undefined) {
          const options = S.parseJsLiteral(args[1]);
          if (options.ok && isRecord(options.value)) {
            const rawMethod = options.value.method;
            if (typeof rawMethod === 'string') method = rawMethod.toUpperCase();
            const rawHeaders = options.value.headers;
            if (isRecord(rawHeaders)) {
              headers = {};
              for (const [key, value] of Object.entries(rawHeaders)) headers[key] = String(value);
            }
            if ('body' in options.value) requestBody = options.value.body;
          }
        }
      }
      continue;
    }

    const assign = S.splitAssignment(item.text);
    if (assign) {
      const name = S.parseVarsLookup(assign.target)?.name;
      if (name && assign.value.includes('.json()')) into = name;
    }
  }

  if (url === null) {
    ctx.warn(line, 'httpCall 的 URL 无法还原', text);
    return null;
  }

  const step: HttpCallStep = { id: ctx.uniqueId(anchor?.id, 'httpCall'), type: 'httpCall', method, url };
  if (headers !== undefined) step.headers = headers;
  if (requestBody !== undefined) step.body = requestBody;
  if (into !== undefined) step.into = into;
  return step;
}

/* ------------------------------------------------------------------- manual */

/** Recover a `manual` step's reason and message from the exported block. */
export function parseManualBlock(text: string): { reason: ManualReason; message: string } | null {
  const literals = S.collectStringLiterals(text);
  const reasonMatch = /Manual step \(([a-z]+)\)/.exec(text);
  if (!reasonMatch) return null;

  const reasons: readonly string[] = ['captcha', 'sms', 'otp', 'confirm', 'other'];
  const raw = reasonMatch[1] ?? 'other';
  const reason = (reasons.includes(raw) ? raw : 'other') as ManualReason;

  // Playwright export keeps the message in `const message = "…";`.
  const declared = /const message\s*=\s*["']((?:\\.|[^"'\\])*)["']\s*;/.exec(text);
  if (declared) return { reason, message: S.unescapeString(declared[1] ?? '') };

  // raw-cdp export inlines it: `Manual step (captcha): solve`.
  for (const literal of literals) {
    const inline = /Manual step \([a-z]+\):\s*([\s\S]*)$/.exec(literal);
    if (inline) return { reason, message: inline[1] ?? '' };
  }
  return { reason, message: '' };
}
